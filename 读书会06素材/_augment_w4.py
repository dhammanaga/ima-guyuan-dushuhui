def patch(txt, old, new, tag):
    n = txt.count(old)
    assert n == 1, f"[{tag}] 匹配数={n}（应为1）: {old[:50]}"
    print(f"  ok {tag}")
    return txt.replace(old, new, 1)

def ins_before(txt, anchor, insert, tag):
    i = txt.index(anchor)
    print(f"  ok {tag} (insert {len(insert)}字)")
    return txt[:i] + insert + txt[i:]

