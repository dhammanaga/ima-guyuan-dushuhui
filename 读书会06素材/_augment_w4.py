def block(tc, since=0):
    """返回以 "> [tc]" 开头的整行（含前缀），找不到则抛错"""
    key = "> [" + tc + "]"
    i = src.index(key, since)
    j = src.index("\n", i)
    return src[i:j]

def quote_fix(s):
    n = s.count('"')
    if n % 2 == 1:
        print(f"  [警告] 引号数奇数({n})，保留原样: {s[:40]}...")
        return s
    return re.sub(r'"([^"]*)"', '“\\1”', s)

def blocks(tcs, since_map):
    out, pos = [], since_map
    for tc in tcs:
        b = block(tc, pos)
        out.append(quote_fix(b))
        pos = src.index("> [" + tc + "]", pos)  # 保持顺序推进
    return "\n>\n".join(out), pos

